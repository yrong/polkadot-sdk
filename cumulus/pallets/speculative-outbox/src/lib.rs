/// Relay storage key for `ParaInclusion::LatestRequires(source, receiver)` (a `StorageDoubleMap`
/// hashed `Twox64Concat` on both keys). The pallet name must match the relay runtime's
/// `construct_runtime!` entry (`ParaInclusion`); a mismatch would make every lookup miss.
pub fn latest_requires_key(source: ParaId, receiver: ParaId) -> Vec<u8> {
	let mut key =
		frame_support::storage::storage_prefix(b"ParaInclusion", b"LatestRequires").to_vec();
	for id in [source, receiver] {
		let encoded = id.encode();
		key.extend_from_slice(&sp_io::hashing::twox_64(&encoded));
		key.extend_from_slice(&encoded);
	}
	key
}

/// Hash a message into its MMR leaf, binding `(source, destination, position)` via
/// `OutgoingMessage::hash_leaf` (`blake2_256`, domain-tagged).
fn message_leaf<T: Config>(dest: ParaId, position: u64, payload: &[u8]) -> H256 {
	let bounded: BoundedVec<u8, MaxSpeculativeMessageLen> =
		BoundedVec::try_from(payload.to_vec()).unwrap_or_default();
	OutgoingMessage::new(T::SelfParaId::get(), dest, position, bounded).hash_leaf::<SpecHasher>()
}

