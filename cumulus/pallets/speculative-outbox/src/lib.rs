mod ack_tests {
	use crate::{
		latest_requires_key,
		mock::{new_test_ext, set_relay_state, RuntimeOrigin, SpeculativeOutbox, Test},
		ConsumedAck, ConsumedWatermark, Error,
	};
	use codec::Encode;
	use cumulus_primitives_core::ParaId;
	use cumulus_test_relay_sproof_builder::RelayStateSproofBuilder;
	use frame_support::{assert_noop, assert_ok, traits::OnFinalize};
	use sp_core::H256;

	const SOURCE: u32 = 1000; // == mock `OutboxParaId` (this parachain)
	const RECEIVER: u32 = 3000;

	/// Record three messages to `RECEIVER` and finalize, returning the committed root (leaf_count
	/// 3).
	fn seed_messages() -> H256 {
		SpeculativeOutbox::record_outbound_messages(
			ParaId::from(RECEIVER),
			vec![b"a".to_vec(), b"b".to_vec(), b"c".to_vec()],
		);
		SpeculativeOutbox::on_finalize(1);
		SpeculativeOutbox::destination_state(ParaId::from(RECEIVER)).unwrap().0
	}

	/// Build a relay state proof committing `LatestRequires<SOURCE, RECEIVER> = (root, block)`.
	fn relay_proof_for(root: H256, block: u32) -> (H256, sp_trie::StorageProof) {
		let mut sproof = RelayStateSproofBuilder::default();
		let key = latest_requires_key(ParaId::from(SOURCE), ParaId::from(RECEIVER));
		sproof.additional_key_values.push((key, (root, block).encode()));
		sproof.into_state_root_and_proof()
	}

	#[test]
	fn note_consumed_advances_watermark_from_relay_proof() {
		new_test_ext().execute_with(|| {
			let receiver = ParaId::from(RECEIVER);
			let root = seed_messages();
			let (state_root, proof) = relay_proof_for(root, 1);

			// Relay parent at block 5: 5 - 1 = 4 >= K (2), so the ack passes the finality gate.
			set_relay_state(5, state_root);
			assert_ok!(SpeculativeOutbox::note_consumed(
				RuntimeOrigin::none(),
				ConsumedAck { proof, receivers: vec![receiver] },
			));
			assert_eq!(ConsumedWatermark::<Test>::get(receiver), 3);
		});
	}

	#[test]
	fn note_consumed_ignores_acks_within_finality_depth() {
		new_test_ext().execute_with(|| {
			let receiver = ParaId::from(RECEIVER);
			let root = seed_messages();
			let (state_root, proof) = relay_proof_for(root, 1);

			// Relay parent at block 2: 2 - 1 = 1 < K (2) — too recent to be revert-safe.
			set_relay_state(2, state_root);
			assert_ok!(SpeculativeOutbox::note_consumed(
				RuntimeOrigin::none(),
				ConsumedAck { proof, receivers: vec![receiver] },
			));
			assert_eq!(ConsumedWatermark::<Test>::get(receiver), 0);
		});
	}

	#[test]
	fn note_consumed_rejects_proof_not_matching_relay_root() {
		new_test_ext().execute_with(|| {
			let receiver = ParaId::from(RECEIVER);
			let root = seed_messages();
			let (_state_root, proof) = relay_proof_for(root, 1);

			// A relay state root that does not match the proof must be rejected.
			set_relay_state(5, H256::repeat_byte(0xff));
			assert_noop!(
				SpeculativeOutbox::note_consumed(
					RuntimeOrigin::none(),
					ConsumedAck { proof, receivers: vec![receiver] },
				),
				Error::<Test>::InvalidRelayProof,
			);
		});
	}

	#[test]
	fn note_consumed_is_noop_for_absent_ack() {
		new_test_ext().execute_with(|| {
			let receiver = ParaId::from(RECEIVER);
			let _root = seed_messages();
			// Proof commits an ack for a *different* receiver, so RECEIVER's lookup is absent.
			let mut sproof = RelayStateSproofBuilder::default();
			let key = latest_requires_key(ParaId::from(SOURCE), ParaId::from(9999));
			sproof.additional_key_values.push((key, (H256::repeat_byte(1), 1u32).encode()));
			let (state_root, proof) = sproof.into_state_root_and_proof();

			set_relay_state(5, state_root);
			assert_ok!(SpeculativeOutbox::note_consumed(
				RuntimeOrigin::none(),
				ConsumedAck { proof, receivers: vec![receiver] },
			));
			assert_eq!(ConsumedWatermark::<Test>::get(receiver), 0);
		});
	}
}

#[cfg(test)]
mod tests {
	use super::*;
	use mmr_lib::util::{MemMMR, MemStore};

	fn leaf(source: u32, dest: u32, position: u64, payload: &[u8]) -> H256 {
		let bounded = BoundedVec::try_from(payload.to_vec()).unwrap();
		OutgoingMessage::new(source.into(), dest.into(), position, bounded)
			.hash_leaf::<SpecHasher>()
	}

	#[test]
	fn peaks_root_matches_mmr_lib() {
		let leaves = [leaf(1, 2, 0, b"msg1"), leaf(1, 2, 1, b"msg2"), leaf(1, 2, 2, b"msg3")];

		// Build using the peaks-only accumulator (same as the pallet).
		let mut acc = Mmr::<SpecHasher>::new();
		for l in &leaves {
			acc.append(*l);
		}

		// Reference: mmr_lib in-memory MMR with the same SpecMerge.
		let store = MemStore::<H256>::default();
		let mut mmr = MemMMR::<H256, SpecMerge<SpecHasher>>::new(0, &store);
		for l in &leaves {
			mmr.push(*l).unwrap();
		}

		assert_eq!(acc.root(), mmr.get_root().unwrap());
	}
}
