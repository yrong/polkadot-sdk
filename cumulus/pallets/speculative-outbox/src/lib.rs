/// Maximum number of consumed payloads pruned in a single [`Pallet::apply_ack`] call. Bounds the
/// weight of an ack; any remaining backlog drains in `on_idle` or on the next ack (follow-up to
/// #12350, see `docs/speculative-messaging-impl-design.md`).
const MAX_PRUNE_PER_CALL: u64 = 100;

/// Maximum total payloads pruned across all destinations in a single `on_idle` sweep.
const MAX_PRUNE_PER_IDLE: u64 = 500;

/// Maximum destinations visited in a single `on_idle` prune sweep.
const MAX_DESTS_PER_IDLE: usize = 50;

/// Maximum number of receiver acks processed in a single [`Pallet::note_consumed`] call. Bounds the
/// extrinsic's weight and proof size.
const MAX_ACKS_PER_CALL: usize = 64;

/// Inherent identifier for the collator-injected consumed-ack inherent. Mirrored by
/// [`client::INHERENT_IDENTIFIER`].
pub const INHERENT_IDENTIFIER: InherentIdentifier = *b"specackn";

/// Collator-supplied relay proof of receiver consumption, carried as an optional inherent and
/// applied by [`Pallet::note_consumed`]. `proof` is a relay state proof against the current relay
/// parent committing the `ParaInclusion::LatestRequires(self, receiver)` entries for `receivers`.
#[derive(Clone, Encode, Decode, DecodeWithMemTracking, PartialEq, Eq, Debug, TypeInfo)]
pub struct ConsumedAck {
	/// Relay state proof containing the `LatestRequires` entries for `receivers`.
	pub proof: sp_trie::StorageProof,
	/// Receivers whose acks are proven and should be applied.
	pub receivers: Vec<ParaId>,
}

/// MMR state for a single destination's subtree (peaks-only representation).
#[derive(Clone, Encode, Decode, TypeInfo, Default)]
pub struct MMRState {
	/// Number of leaves inserted so far (the MMR `size`).
	pub leaf_count: u64,
	/// MMR peaks — O(log n) hashes sufficient to reconstruct the subtree root.
	pub peaks: Vec<H256>,
	/// Total `mmr_lib` node count (positions), tracked so the persistent node store
	/// ([`OutgoingMmrNodes`]) can be reopened as `MMR::new(mmr_size, store)` for proof generation.
	pub mmr_size: u64,
}

/// Persistent `mmr_lib` store for a destination's outbound MMR nodes, backed by
/// [`OutgoingMmrNodes`]. Lets proofs be generated by reading stored nodes (O(log n)) instead of
/// replaying every payload, so consumed payloads can be pruned without breaking proof generation
/// (follow-up to #12350).
struct OutboxStore<T>(ParaId, core::marker::PhantomData<T>);

impl<T> OutboxStore<T> {
	fn new(dest: ParaId) -> Self {
		Self(dest, core::marker::PhantomData)
	}
}

impl<T: Config> MMRStoreReadOps<H256> for OutboxStore<T> {
	fn get_elem(&self, pos: u64) -> mmr_lib::Result<Option<H256>> {
		Ok(OutgoingMmrNodes::<T>::get(self.0, pos))
	}
}

impl<T: Config> MMRStoreWriteOps<H256> for OutboxStore<T> {
	fn append(&mut self, pos: u64, elems: Vec<H256>) -> mmr_lib::Result<()> {
		for (i, elem) in elems.into_iter().enumerate() {
			OutgoingMmrNodes::<T>::insert(self.0, pos + i as u64, elem);
		}
		Ok(())
	}
}

